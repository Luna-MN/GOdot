package main

import (
	"fmt"
	"log"
	"net/http"
	"os"
	"server/internal"
	"server/internal/server"
	"server/internal/server/clients"
	"server/internal/server/clients/ENet"
)

func main() {
	// Define the game hub
	hub := server.NewHub()

	// define the handler for the websocket connections
	http.HandleFunc("/ws", func(w http.ResponseWriter, r *http.Request) {
		hub.Serve(clients.NewWebSocketClient, w, r)
	})
	ENet.InitEnet(hub)
	go hub.Run()
	addr := fmt.Sprintf(":%d", internal.WSport)

	certFile := "cert/server.crt"
	keyFile := "cert/server.key"

	log.Printf("Server started on %s", addr)

	if _, err := os.Stat(certFile); err != nil {
		log.Fatalf("Certificate file not found: %s: %v run openssl req -x509 -newkey rsa:4096 -keyout server/cert/server.key -out server/cert/server.crt -days 365 -nodes", certFile, err)
	}

	if _, err := os.Stat(keyFile); err != nil {
		log.Fatalf("Key file not found: %s: %v run openssl req -x509 -newkey rsa:4096 -keyout server/cert/server.key -out server/cert/server.crt -days 365 -nodes", keyFile, err)
	}

	log.Printf("Server started on %s", addr)
	// WARNING: this is not secure, the certificate and key are generated by me and should be changed before full launch
	err := http.ListenAndServeTLS(addr, certFile, keyFile, nil)
	if err != nil {
		log.Fatalf("Failed to start server: %v", err)
	}
}
